/**
 * Generates src/core/db/schema-sql.ts from prisma/migrations.
 * Run: bun run schema:sync   (after every `prisma migrate dev`)
 *
 * CREATE statements are rewritten to IF NOT EXISTS so that `lps init`
 * stays idempotent even when the bookkeeping "Meta" table is created first.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const MIGRATIONS_DIR = join(import.meta.dir, "..", "prisma", "migrations");
const OUT_FILE = join(import.meta.dir, "..", "src", "core", "db", "schema-sql.ts");

function makeIdempotent(sql: string): string {
  return sql
    .replace(/CREATE TABLE /g, "CREATE TABLE IF NOT EXISTS ")
    .replace(/CREATE UNIQUE INDEX /g, "CREATE UNIQUE INDEX IF NOT EXISTS ")
    .replace(/CREATE INDEX /g, "CREATE INDEX IF NOT EXISTS ");
}

const dirs = readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

if (dirs.length === 0) {
  console.error(`No migrations found in ${MIGRATIONS_DIR}`);
  process.exit(1);
}

const entries = dirs.map((name) => {
  const sqlPath = join(MIGRATIONS_DIR, name, "migration.sql");
  if (!existsSync(sqlPath)) {
    console.error(`Missing migration.sql in ${name}`);
    process.exit(1);
  }
  return { name, sql: makeIdempotent(readFileSync(sqlPath, "utf8")) };
});

const body = `// AUTO-GENERATED by \`bun run schema:sync\` from prisma/migrations. Do not edit.
export type Migration = { name: string; sql: string };

export const MIGRATIONS: Migration[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT_FILE, body);
console.log(`Wrote ${OUT_FILE} (${entries.length} migration(s))`);
